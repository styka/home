// Bakes the target-architecture book ("Omnia 🧐 — architektura docelowa") from
// content/architektura/manifest.json + per-chapter Markdown into a generated TS
// module for the admin reader at /admin/architektura-docelowa.
//
// Mirrors scripts/copy-audyt-podsumowanie.js, with one addition: the whole book is
// also concatenated into a single Markdown blob wrapped in a pipeline prompt, so the
// reader can offer a one-click "copy as Claude Code prompt" button. Building that
// blob here (not in the browser) keeps the client bundle free of 14 chapters twice.
//
// Source of truth: content/architektura/*. Run as an early step of `npm run build`;
// the generated module is committed so `npm run dev` works on a fresh clone.
const fs = require("fs")
const path = require("path")

const ROOT = path.resolve(__dirname, "..")
const CONTENT_DIR = path.join(ROOT, "content", "architektura")
const MANIFEST_PATH = path.join(CONTENT_DIR, "manifest.json")

function readChapter(slug) {
  const abs = path.join(CONTENT_DIR, `${slug}.md`)
  try {
    return { content: fs.readFileSync(abs, "utf8"), mtime: fs.statSync(abs).mtime.toISOString() }
  } catch {
    return null
  }
}

const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, "utf8"))

const chapters = manifest.chapters.map((c) => {
  const found = readChapter(c.slug)
  const markdown = found ? found.content : ""
  const hasContent = markdown.trim().length > 40
  return {
    slug: c.slug,
    number: c.number ?? "",
    part: c.part ?? "",
    title: c.title,
    summary: c.summary ?? "",
    status: hasContent ? (c.draft ? "draft" : "done") : "planned",
    markdown,
    words: markdown.trim() ? markdown.trim().split(/\s+/).length : 0,
    updatedAt: found ? found.mtime : null,
  }
})

const meta = {
  title: manifest.title ?? "Architektura docelowa",
  subtitle: manifest.subtitle ?? "",
  auditDate: manifest.auditDate ?? "",
}

// Prompt uruchamiający pipeline: instrukcja + cały dokument, rozdział po rozdziale.
const prompt =
  (manifest.promptIntro ?? "") +
  chapters
    .filter((c) => c.markdown.trim())
    .map((c) => c.markdown.trim())
    .join("\n\n---\n\n") +
  "\n"

const banner = `// AUTO-GENERATED by scripts/copy-architektura.js — DO NOT EDIT BY HAND.
// Regenerated on every \`npm run build\`. Holds the target-architecture book for the
// admin reader at /admin/architektura-docelowa.
// Edit content/architektura/*.md instead.
`

const body =
  banner +
  `import type { AudytChapter } from "@/generated/audyt-book"\n\n` +
  `export const ARCHITEKTURA_META = ${JSON.stringify(meta, null, 2)}\n\n` +
  `export const ARCHITEKTURA_CHAPTERS: AudytChapter[] = ${JSON.stringify(chapters, null, 2)}\n\n` +
  `/** Cały dokument opakowany w prompt uruchamiający spec-driven pipeline. */\n` +
  `export const ARCHITEKTURA_PROMPT = ${JSON.stringify(prompt)}\n\n` +
  `export const ARCHITEKTURA_GENERATED_AT = ${JSON.stringify(new Date().toISOString())}\n`

const outDir = path.join(ROOT, "src", "generated")
fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(path.join(outDir, "architektura-book.ts"), body, "utf8")

const done = chapters.filter((c) => c.status === "done").length
const words = chapters.reduce((sum, c) => sum + c.words, 0)
console.log(
  `✓ copy-architektura: ${chapters.length} rozdziałów (done ${done}, ${words} słów), prompt ${prompt.length} znaków → src/generated/architektura-book.ts`
)
