// 108 — Pieczenie PRZEWODNIKÓW UŻYTKOWNIKA (content/przewodniki/manifest.json + rozdziały .md)
// do wygenerowanego modułu TS, z którego korzysta dział /guide.
//
// Wzorzec: scripts/copy-audyt-podsumowanie.js. Jedna świadoma różnica: rozdział zadeklarowany
// w manifeście, a pozbawiony treści, **wywala build**. W książkach audytu brak pliku jest legalnym
// stanem „rozdział zaplanowany", bo tamte książki rosną w czasie. Przewodnik użytkownika albo jest
// kompletny, albo go nie ma — dziura w spisie treści nie jest tam informacją, tylko usterką.
//
// Źródło prawdy: content/przewodniki/*. Uruchamiane jako wczesny krok `npm run build`;
// wygenerowany moduł jest commitowany, żeby `npm run dev` działał na świeżym klonie.
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const CONTENT_DIR = path.join(ROOT, "content", "przewodniki");
const MANIFEST_PATH = path.join(CONTENT_DIR, "manifest.json");

/**
 * Markdown bez składni — do wyszukiwania po treści.
 *
 * Liczone TUTAJ, a nie w przeglądarce: wyszukiwarka działa na tekście, więc parsowanie markdownu
 * po stronie klienta tylko po to, żeby w nim szukać, byłoby pracą wykonywaną u każdego czytelnika
 * od nowa. Kolejność ma znaczenie — bloki kodu wypadają przed obróbką znaczników, inaczej ich
 * zawartość zostałaby w indeksie jako „treść".
 */
function naTekst(md) {
  return md
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/`[^`]*`/g, " ")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/^\s{0,3}#{1,6}\s+/gm, "")
    .replace(/^\s{0,3}>\s?/gm, "")
    .replace(/^\s*[-*+]\s+/gm, "")
    .replace(/^\s*\d+\.\s+/gm, "")
    .replace(/[*_~|]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, "utf8"));
const bledy = [];

const przewodniki = manifest.przewodniki.map((p) => {
  const rozdzialy = p.rozdzialy.map((r) => {
    const abs = path.join(CONTENT_DIR, p.slug, `${r.slug}.md`);
    let markdown = "";
    let mtime = null;
    try {
      markdown = fs.readFileSync(abs, "utf8");
      mtime = fs.statSync(abs).mtime.toISOString();
    } catch {
      bledy.push(`brak pliku: content/przewodniki/${p.slug}/${r.slug}.md`);
      return null;
    }
    if (markdown.trim().length < 40) {
      bledy.push(`pusty rozdział: content/przewodniki/${p.slug}/${r.slug}.md`);
      return null;
    }
    return {
      slug: r.slug,
      title: r.title,
      summary: r.summary ?? "",
      markdown,
      tekst: naTekst(markdown),
      words: markdown.trim().split(/\s+/).length,
      updatedAt: mtime,
    };
  });

  const zdrowe = rozdzialy.filter(Boolean);
  // `updatedAt` przewodnika = najnowszy z jego rozdziałów. Czytelnik ma widzieć, kiedy treść była
  // ostatnio dotykana — a nie kiedy powstał pierwszy rozdział.
  const updatedAt = zdrowe.reduce((max, r) => (!max || r.updatedAt > max ? r.updatedAt : max), null);
  return {
    slug: p.slug,
    moduleId: p.moduleId ?? null,
    title: p.title,
    subtitle: p.subtitle ?? "",
    summary: p.summary ?? "",
    rozdzialy: zdrowe,
    words: zdrowe.reduce((s, r) => s + r.words, 0),
    updatedAt,
  };
});

if (bledy.length) {
  console.error("✗ copy-przewodniki: rozdziały zadeklarowane w manifeście bez treści:");
  for (const b of bledy) console.error(`   • ${b}`);
  console.error(
    "\n  Przewodnik użytkownika albo jest kompletny, albo go nie ma: dziura w spisie treści to\n" +
      "  usterka, nie informacja. Dopisz treść albo usuń rozdział z content/przewodniki/manifest.json."
  );
  process.exit(1);
}

const banner = `// AUTO-GENERATED by scripts/copy-przewodniki.js — DO NOT EDIT BY HAND.
// Regenerowane przy każdym \`npm run build\`. Trzyma przewodniki użytkownika dla działu /guide.
// Edytuj content/przewodniki/* zamiast tego pliku.
`;

const typy = `
export interface RozdzialPrzewodnika {
  slug: string;
  title: string;
  summary: string;
  /** Treść rozdziału. Na HTML zamienia ją \`markdownToHtml\` — po stronie SERWERA. */
  markdown: string;
  /** Ta sama treść bez składni markdown — do wyszukiwania. Liczona w czasie builda. */
  tekst: string;
  words: number;
  updatedAt: string | null;
}

export interface Przewodnik {
  slug: string;
  /** Id modułu z rejestru \`MODULES\`, którego dotyczy przewodnik. \`null\` = przewodnik niemodułowy. */
  moduleId: string | null;
  title: string;
  subtitle: string;
  summary: string;
  rozdzialy: RozdzialPrzewodnika[];
  words: number;
  updatedAt: string | null;
}
`;

const body =
  banner +
  typy +
  `\nexport const PRZEWODNIKI: Przewodnik[] = ${JSON.stringify(przewodniki, null, 2)}\n\n` +
  `export const PRZEWODNIKI_GENERATED_AT = ${JSON.stringify(new Date().toISOString())}\n`;

const outDir = path.join(ROOT, "src", "generated");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "przewodniki.ts"), body, "utf8");

const rozdzialow = przewodniki.reduce((s, p) => s + p.rozdzialy.length, 0);
const slow = przewodniki.reduce((s, p) => s + p.words, 0);
console.log(
  `✓ copy-przewodniki: ${przewodniki.length} przewodników, ${rozdzialow} rozdziałów, ${slow} słów → src/generated/przewodniki.ts`
);
